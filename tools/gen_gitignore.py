"""Generate the default-ignore .gitignore from public-paths.txt (the only list of what this repository publishes).

The checkout is the deployment (~/llm-serving): weights links, venvs, logs, keys, fork checkouts and experiments live
in the same tree, so everything is ignored and the public paths are re-included one by one: each parent directory is
re-included and its contents ignored again, then the listed entry is re-included (`dir/**` = the whole directory).
Later rules win, so the trailing block keeps caches and secrets out even inside public directories.
To publish a new file: add it to public-paths.txt, run this tool, commit both (never `git add -f`).
Usage: gen_gitignore.py [--check]   (--check: exit 1 when .gitignore is not the generated text)
"""
import argparse
import sys
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[1]
LIST, OUT = ROOT / "public-paths.txt", ROOT / ".gitignore"
PRIVATE_IN_PUBLIC = ["__pycache__/", "*.pyc", ".DS_Store", ".venv*/", "*.bak*", "*.log", "*.sqlite*", ".api_key",
                     "api_key", ".env", ".env.*", "serving-values.json", "serving.env", "private-literals",
                     "*.safetensors", "*.gguf", "/docs/handoff/"]


def entries(text):
    out = []
    for raw in text.splitlines():
        entry = raw.strip()
        if entry and not entry.startswith("#"):
            out.append(entry)
    return out


def generate(text):
    lines = ["# Generated by tools/gen_gitignore.py from public-paths.txt: everything is ignored, the public paths are",
             "# re-included. Add a public file to public-paths.txt and regenerate; never `git add -f`.", "/*"]
    seen = set()
    for entry in entries(text):
        whole = entry.endswith("/**")
        path = PurePosixPath(entry[:-3] if whole else entry)
        parts = path.parts
        for k in range(1, len(parts)):
            d = "/".join(parts[:k])
            if d not in seen:
                seen.add(d)
                lines += [f"!/{d}/", f"/{d}/*"]
        lines.append(f"!/{path}/" if whole else f"!/{path}")
    lines += ["", "# private or generated even inside public directories"] + PRIVATE_IN_PUBLIC
    return "\n".join(lines) + "\n"


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", action="store_true")
    a = p.parse_args(argv)
    text = generate(LIST.read_text())
    if a.check:
        ok = OUT.is_file() and OUT.read_text() == text
        print(".gitignore matches public-paths.txt" if ok else ".gitignore differs from public-paths.txt; run tools/gen_gitignore.py")
        return 0 if ok else 1
    OUT.write_text(text)
    print(f"wrote .gitignore ({len(entries(LIST.read_text()))} public entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
